#!/usr/bin/env python3
"""Generate include/mw_font_aa.h — anti-aliased proportional UI font.

Renders ASCII 32..126 from DejaVu Sans (regular + bold) at two pixel
heights (15 UI, 12 small) with 4bpp coverage, packed 2 pixels per byte.
The MiniWin engine embeds this header so screenshots get modern
letterforms instead of the 8x8 bitmap font (SW-GUI7).
"""
from PIL import Image, ImageDraw, ImageFont
import os

OUT = "/home/z/my-project/workspace/miniwin-engineering/include/mw_font_aa.h"
DEJA = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
DEJA_B = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"

FACES = [("n", DEJA, 15), ("b", DEJA_B, 15), ("s", DEJA, 12)]

CHRS = list(range(32, 127))

def render(path, px):
    font = ImageFont.truetype(path, px)
    glyphs = []
    for ch in CHRS:
        im = Image.new("L", (px * 3, px * 3), 0)
        d = ImageDraw.Draw(im)
        d.text((px, px // 2), chr(ch), font=font, fill=255)
        bb = im.getbbox()  # (l,t,r,b)
        if bb is None:
            glyphs.append((0, 0, 0, 0, b""))
